from pathlib import Path

import pandas as pd


项目目录 = Path(__file__).resolve().parents[1]

处理后数据目录 = (
    项目目录
    / "数据"
    / "处理后数据"
)

报告目录 = 项目目录 / "报告"

报告目录.mkdir(
    parents=True,
    exist_ok=True
)

正常销售文件 = (
    处理后数据目录
    / "正常销售.csv"
)

客户汇总文件 = (
    处理后数据目录
    / "客户汇总.csv"
)

月度销售文件 = (
    处理后数据目录
    / "月度销售.csv"
)

国家销售文件 = (
    处理后数据目录
    / "国家销售.csv"
)

商品销售文件 = (
    处理后数据目录
    / "商品销售.csv"
)

RFM分层文件 = (
    处理后数据目录
    / "RFM客户分层汇总.csv"
)

客户留存率文件 = (
    处理后数据目录
    / "客户留存率.csv"
)



需要的文件 = [
    正常销售文件,
    客户汇总文件,
    月度销售文件,
    国家销售文件,
    商品销售文件,
    RFM分层文件,
    客户留存率文件
]

print("===== 检查分析文件 =====")

for 文件 in 需要的文件:
    print(
        文件.name,
        "存在：",
        文件.exists()
    )

    if not 文件.exists():
        raise FileNotFoundError(
            f"缺少分析文件：{文件}"
        )


正常销售数据 = pd.read_csv(
    正常销售文件,
    dtype={
        "InvoiceNo": "string",
        "StockCode": "string",
        "CustomerID": "string"
    }
)

客户汇总表 = pd.read_csv(
    客户汇总文件,
    dtype={
        "CustomerID": "string"
    }
)

月度销售表 = pd.read_csv(
    月度销售文件
)

国家销售表 = pd.read_csv(
    国家销售文件
)

商品销售表 = pd.read_csv(
    商品销售文件,
    dtype={
        "StockCode": "string"
    }
)

RFM分层表 = pd.read_csv(
    RFM分层文件
)

客户留存率表 = pd.read_csv(
    客户留存率文件
)

print("\n所有分析文件读取成功！")




总销售额 = (
    正常销售数据["Sales"]
    .sum()
)

订单数量 = (
    正常销售数据["InvoiceNo"]
    .nunique()
)

客户数量 = (
    正常销售数据["CustomerID"]
    .nunique()
)

商品销售数量 = (
    正常销售数据["Quantity"]
    .sum()
)

平均客单价 = (
    总销售额
    / 订单数量
)

平均每单商品数 = (
    商品销售数量
    / 订单数量
)


不完整月份标记 = (
    月度销售表["是否不完整月份"]
    .astype(str)
    .str.lower()
    .eq("true")
)

完整月份数据 = 月度销售表[
    ~不完整月份标记
].copy()

最佳月份记录 = 完整月份数据.loc[
    完整月份数据["销售额"].idxmax()
]

最佳月份 = (
    最佳月份记录["YearMonth"]
)

最佳月份销售额 = (
    最佳月份记录["销售额"]
)



英国记录 = 国家销售表[
    国家销售表["Country"]
    == "United Kingdom"
].iloc[0]

英国销售额占比 = (
    英国记录["销售额占比%"]
)

海外市场表 = (
    国家销售表[
        国家销售表["Country"]
        != "United Kingdom"
    ]
    .sort_values(
        "销售额",
        ascending=False
    )
)

最大海外市场记录 = 海外市场表.iloc[0]

最大海外市场 = (
    最大海外市场记录["Country"]
)

最大海外市场销售额 = (
    最大海外市场记录["销售额"]
)



服务费用代码 = [
    "POST",
    "DOT",
    "M",
    "BANK CHARGES",
    "C2",
    "PADS"
]

实际商品表 = 商品销售表[
    ~商品销售表["StockCode"].isin(
        服务费用代码
    )
].copy()

销售额最高商品记录 = 实际商品表.loc[
    实际商品表["销售额"].idxmax()
]

销量最高商品记录 = 实际商品表.loc[
    实际商品表["销量"].idxmax()
]

销售额最高商品 = (
    销售额最高商品记录["商品名称"]
)

销售额最高商品金额 = (
    销售额最高商品记录["销售额"]
)

销量最高商品 = (
    销量最高商品记录["商品名称"]
)

销量最高商品数量 = (
    销量最高商品记录["销量"]
)



客户总数 = len(客户汇总表)

一次性客户数量 = (
    客户汇总表["购买次数"] == 1
).sum()

复购客户数量 = (
    客户汇总表["购买次数"] >= 2
).sum()

复购率 = (
    复购客户数量
    / 客户总数
    * 100
)



销售贡献最高分层记录 = RFM分层表.loc[
    RFM分层表["总销售额"].idxmax()
]

销售贡献最高分层 = (
    销售贡献最高分层记录["客户分层"]
)

该分层销售额占比 = (
    销售贡献最高分层记录["销售额占比%"]
)

该分层客户占比 = (
    销售贡献最高分层记录["客户占比%"]
)



第二月列名 = "2"

if 第二月列名 in 客户留存率表.columns:
    第二月留存数据 = pd.to_numeric(
        客户留存率表[第二月列名],
        errors="coerce"
    ).dropna()

    第二月留存率中位数 = (
        第二月留存数据.median()
    )

else:
    第二月留存率中位数 = float("nan")




项目总结 = f"""
电商销售与客户留存分析项目总结
================================

一、项目背景
本项目分析一家英国线上零售公司的交易数据。
数据覆盖2010年12月至2011年12月，
目标是将原始交易明细转换为销售、客户和留存方面的业务洞察。

二、整体销售表现
正常销售额：£{总销售额:,.2f}
正常订单数量：{订单数量:,}
可识别客户数量：{客户数量:,}
商品销售数量：{商品销售数量:,}
平均客单价：£{平均客单价:,.2f}
平均每单商品数：{平均每单商品数:,.2f}

三、月度销售表现
销售额最高的完整月份是{最佳月份}，
当月销售额为£{最佳月份销售额:,.2f}。

数据最后一个月不完整，
因此没有直接参与完整月份之间的表现比较。

四、国家市场表现
英国贡献了整体销售额的{英国销售额占比:.2f}%，
说明公司销售高度集中于本土市场。

英国以外最大的市场是{最大海外市场}，
销售额为£{最大海外市场销售额:,.2f}。

五、商品表现
销售额最高的实际商品是：
{销售额最高商品}
销售额为£{销售额最高商品金额:,.2f}。

销量最高的实际商品是：
{销量最高商品}
销量为{int(销量最高商品数量):,}件。

销量最高与销售额最高的商品不一定相同，
因为商品价格和销售数量会共同影响销售额。

六、客户复购表现
可识别客户总数：{客户总数:,}
一次性客户：{一次性客户数量:,}
复购客户：{复购客户数量:,}
整体复购率：{复购率:.2f}%

复购率说明客户在整个观察期内是否再次购买，
但仍然需要结合留存分析判断客户在不同月份的持续活跃情况。

七、RFM客户分层
销售贡献最高的客户群体是：
{销售贡献最高分层}

该群体客户占比为{该分层客户占比:.2f}%，
销售额占比为{该分层销售额占比:.2f}%。

这说明不同客户群体对销售额的贡献并不均衡，
企业应该针对不同客户群体采取不同运营策略。

八、客户留存
各客户群组第2月留存率的中位数约为：
{第二月留存率中位数:.2f}%

这说明首次购买并不等于形成稳定客户关系。
企业应重点关注首次购买后的第二次转化。

九、业务建议
1. 优先维护英国核心市场和高价值客户。
2. 重点研究表现较好的海外市场。
3. 对高销量和高销售额商品分别制定库存与推广策略。
4. 对一次性客户设计第二次购买激励。
5. 对高价值流失风险客户进行个性化召回。
6. 为冠军客户和忠诚客户提供会员权益。
7. 持续监测取消订单、异常数量和零价格交易。
8. 月度报告必须标明不完整月份。

十、项目限制
1. 数据没有商品成本，无法计算利润。
2. 数据没有营销渠道，无法进行渠道归因。
3. 部分交易缺少客户编号，无法用于客户行为分析。
4. 数据最后一个月不完整。
5. 正常销售额不完全等同于财务口径的净收入。
"""



print("\n" + 项目总结)

项目总结文件 = (
    报告目录
    / "项目总结.txt"
)

项目总结文件.write_text(
    项目总结.strip(),
    encoding="utf-8"
)

print("\n===== 项目总结保存完成 =====")
